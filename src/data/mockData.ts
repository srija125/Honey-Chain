// Helper to compute deterministic simulated SHA-256 hash
export function generateSHA256Hash(
  bottleId: string,
  eventType: string = 'EVENT',
  timestamp: string = new Date().toISOString(),
  sensorId: string = 'SNS-001'
): string {
  const input = `${bottleId}|${eventType}|${timestamp}|${sensorId}|HONEY_CHAIN_SALT_2026`;
  let hash = 0;
  for (let i = 0; i < input.length; i++) {
    const char = input.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0; // Convert to 32bit integer
  }
  const hex1 = Math.abs(hash).toString(16).padStart(8, '0');
  const hex2 = (Math.abs(hash * 31) >>> 0).toString(16).padStart(8, '0');
  const hex3 = (Math.abs(hash * 137) >>> 0).toString(16).padStart(8, '0');
  const hex4 = (Math.abs(hash * 991) >>> 0).toString(16).padStart(8, '0');
  const hex5 = (Math.abs(hash * 1543) >>> 0).toString(16).padStart(8, '0');
  const hex6 = (Math.abs(hash * 2879) >>> 0).toString(16).padStart(8, '0');
  const hex7 = (Math.abs(hash * 3821) >>> 0).toString(16).padStart(8, '0');
  const hex8 = (Math.abs(hash * 4099) >>> 0).toString(16).padStart(8, '0');
  return `0x${hex1}${hex2}${hex3}${hex4}${hex5}${hex6}${hex7}${hex8}`;
}

